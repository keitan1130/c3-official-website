import { assetFile, loadContent, localAsset, localFile } from "./load.ts";
import { markdownAssetEdits } from "./markdownAssets.ts";

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve("content");
const OUTPUT = path.resolve("src/generated/contentData.ts");

export function prepareContent(root = ROOT, output = OUTPUT) {
  const stagedFiles = new Set<string>();
  const stagingDirectory = path.join(path.dirname(output), "contentFiles");
  const importPath = (file: string) => {
    // Vite treats # and ? in filesystem imports as URL delimiters. Keep the
    // source name intact and import a generated copy with a safe filename.
    let relative = path
      .relative(path.dirname(output), file)
      .split(path.sep)
      .join("/");
    if (/[?#]/.test(relative)) {
      const source = fs.readFileSync(file);
      const hash = createHash("sha256").update(source).digest("hex");
      const name = hash + path.extname(file).replace(/[?#]/g, "-");
      fs.mkdirSync(stagingDirectory, { recursive: true });
      const staged = path.join(stagingDirectory, name);
      if (!fs.existsSync(staged)) fs.writeFileSync(staged, source);
      stagedFiles.add(name);
      relative = `./contentFiles/${name}`;
    }
    return relative;
  };
  const imports = new Map<string, string>();
  const importAsset = (file: string) => {
    const existing = imports.get(file);
    if (existing !== undefined) return existing;
    const name = `ASSET_${imports.size}`;
    imports.set(file, name);
    return name;
  };
  const assetReference = (directory: string, relative: string) =>
    importAsset(assetFile(directory, relative));
  const bodyLoader = (directory: string, relative: string) => {
    const file = localFile(directory, relative);
    const text = fs.readFileSync(file, "utf8");
    // Collision-free tokens let generated expressions use Vite asset imports
    // without replacing matching text elsewhere in the document.
    let prefix = "C3_LOCAL_ASSET_";
    while (text.includes(prefix)) prefix += "_";
    const tokens: { token: string; value: string }[] = [];
    const edits = markdownAssetEdits(text, (url, _context, kind) => {
      const asset = localAsset(path.dirname(file), url, directory, kind);
      if (!asset) return url;
      const token = `${prefix}${tokens.length}_END`;
      const value = `assetUrl(${importAsset(asset.file)} + ${JSON.stringify(asset.suffix)})`;
      // Both Markdown destinations and HTML attributes decode character
      // references again when rendered, so escape their ampersands once.
      tokens.push({ token, value: `${value}.replaceAll("&", "&amp;")` });
      return token;
    });
    const expression = (value: string) => {
      const parts = [];
      let offset = 0;
      const pattern = new RegExp(`${prefix}\\d+_END`, "g");
      for (const match of value.matchAll(pattern)) {
        parts.push(
          JSON.stringify(value.slice(offset, match.index)),
          tokens[Number(match[0].slice(prefix.length, -4))].value,
        );
        offset = match.index + match[0].length;
      }
      parts.push(JSON.stringify(value.slice(offset)));
      return parts.join(" + ");
    };
    const parts = [];
    let offset = 0;
    for (const edit of edits) {
      parts.push(
        `module.default.slice(${offset}, ${edit.start})`,
        expression(edit.value),
      );
      offset = edit.end;
    }
    parts.push(`module.default.slice(${offset})`);
    return `() => import(${JSON.stringify(`${importPath(file)}?raw`)}).then(module => ${parts.join(" + ")})`;
  };
  const { news, communities, about } = loadContent(root);
  const newsData = news.map(({ value: item, directory }) => {
    const metadata = {
      id: item.id,
      kind: "news",
      title: item.title,
      digest: item.digest,
      publishedDate: item.publishedDate,
    };
    return `{...${JSON.stringify(metadata)},thumbnail:${assetReference(directory, item.thumbnail)},body:${bodyLoader(directory, item.body)}}`;
  });
  const communityData = communities.map(
    ({ value: item, directory }) =>
      `{...${JSON.stringify({ slug: item.slug, name: item.name, domain: item.domain })},mp4:${assetReference(directory, item.mp4)},body:${bodyLoader(directory, item.body)}}`,
  );
  const body = `{about:{summary:${JSON.stringify(about.value.summary)},body:${bodyLoader(about.directory, about.value.body)}},communities:[${communityData.join(",")}],news:[${newsData.join(",")}]}`;
  const preamble = [...imports]
    .map(
      ([file, name]) =>
        `import ${name} from ${JSON.stringify(`${importPath(file)}?url&no-inline`)};`,
    )
    .join("\n");
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(
    output,
    `// Generated by scripts/content/generate.ts. Edit content/ instead.\n${preamble}\nimport type { ContentData } from "@/shared/types/content";\nconst assetUrl = (url: string) => url.replace(/[\\s<>"'()\\[\\]\u0060\\\\]/gu, character => encodeURIComponent(character).replace(/[!'()*]/g, character => "%" + character.charCodeAt(0).toString(16)));\nconst CONTENT_DATA: ContentData = ${body};\nexport default CONTENT_DATA;\n`,
  );
  if (fs.existsSync(stagingDirectory)) {
    for (const name of fs.readdirSync(stagingDirectory)) {
      if (!stagedFiles.has(name)) fs.rmSync(path.join(stagingDirectory, name));
    }
  }
  return {
    news: news.length,
    communities: communities.length,
    assets: imports.size,
  };
}
