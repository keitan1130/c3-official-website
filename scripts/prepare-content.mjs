import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { loadContent, localFile } from "./local-content.mjs";

const ROOT = path.resolve("content");
const OUTPUT = path.resolve("src/generated/contentData.ts");

export function prepareContent(root = ROOT, output = OUTPUT) {
  const imports = new Map();
  const assetReference = (directory, relative) => {
    const file = localFile(directory, relative);
    if (!imports.has(file)) imports.set(file, `ASSET_${imports.size}`);
    return imports.get(file);
  };
  const bodyLoader = (directory, relative) => {
    const file = localFile(directory, relative);
    const text = fs.readFileSync(file, "utf8");
    const matches = [...new Set(text.match(/\.\/assets\/[^\s<>"'()\]]+/g) ?? [])];
    const replacements = matches.sort((a,b) => b.length-a.length).map((relative) => `.replaceAll(${JSON.stringify(relative)}, ${assetReference(directory, relative)})`).join("");
    const importPath = path.relative(path.dirname(output), file).split(path.sep).join("/");
    return `() => import(${JSON.stringify(importPath + "?raw")}).then(module => module.default${replacements})`;
  };
  const { news, communities, about } = loadContent(root);
  const newsData = news.map(({value:item,directory}) => {
    const metadata = { id:item.id, kind:"news", title:item.title, digest:item.digest, publishedDate:item.publishedDate };
    return `{...${JSON.stringify(metadata)},thumbnail:${assetReference(directory,item.thumbnail)},body:${bodyLoader(directory,item.body)}}`;
  });
  const communityData = communities.map(({value:item,directory}) => `{...${JSON.stringify({slug:item.slug,name:item.name,domain:item.domain})},mp4:${assetReference(directory,item.mp4)},body:${bodyLoader(directory,item.body)}}`);
  const body = `{about:{summary:${JSON.stringify(about.value.summary)},body:${bodyLoader(about.directory,about.value.body)}},communities:[${communityData.join(",")}],news:[${newsData.join(",")}]}`;
  const preamble = [...imports].map(([file,name]) => `import ${name} from ${JSON.stringify(path.relative(path.dirname(output),file).split(path.sep).join("/")+"?url")};`).join("\n");
  fs.mkdirSync(path.dirname(output),{recursive:true});
  fs.writeFileSync(output, `// Generated by scripts/prepare-content.mjs. Edit content/ instead.\n${preamble}\nimport type { ContentData } from "@/shared/types/content";\nconst CONTENT_DATA: ContentData = ${body};\nexport default CONTENT_DATA;\n`);
  return {news:news.length,communities:communities.length,assets:imports.size};
}
