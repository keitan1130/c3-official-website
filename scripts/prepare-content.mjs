import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { loadContent, localFile, localAsset } from "./local-content.mjs";
import { markdownAssetEdits } from "./markdown-assets.mjs";

const ROOT = path.resolve("content");
const OUTPUT = path.resolve("src/generated/contentData.ts");

export function prepareContent(root = ROOT, output = OUTPUT) {
  const imports = new Map();
  const importAsset = (file) => {
    if (!imports.has(file)) imports.set(file, `ASSET_${imports.size}`);
    return imports.get(file);
  };
  const assetReference = (directory, relative) => importAsset(localFile(directory, relative));
  const bodyLoader = (directory, relative) => {
    const file = localFile(directory, relative);
    const text = fs.readFileSync(file, "utf8");
    // Collision-free tokens let generated expressions use Vite asset imports
    // without replacing matching text elsewhere in the document.
    let prefix = "C3_LOCAL_ASSET_";
    while (text.includes(prefix)) prefix += "_";
    const tokens = [];
    const edits = markdownAssetEdits(text, (url, context) => {
      const asset = localAsset(path.dirname(file), url, directory);
      if (!asset) return url;
      const token = `${prefix}${tokens.length}_END`;
      const value = `assetUrl(${importAsset(asset.file)} + ${JSON.stringify(asset.suffix)})`;
      tokens.push({ token, value: context === "html" ? `${value}.replaceAll("&", "&amp;")` : value });
      return token;
    });
    const expression = (value) => {
      const parts = [];
      let offset = 0;
      const pattern = new RegExp(`${prefix}\\d+_END`, "g");
      for (const match of value.matchAll(pattern)) {
        parts.push(JSON.stringify(value.slice(offset, match.index)), tokens[Number(match[0].slice(prefix.length, -4))].value);
        offset = match.index + match[0].length;
      }
      parts.push(JSON.stringify(value.slice(offset)));
      return parts.join(" + ");
    };
    const parts = [];
    let offset = 0;
    for (const edit of edits) {
      parts.push(`module.default.slice(${offset}, ${edit.start})`, expression(edit.value));
      offset = edit.end;
    }
    parts.push(`module.default.slice(${offset})`);
    const importPath = path.relative(path.dirname(output), file).split(path.sep).join("/");
    return `() => import(${JSON.stringify(importPath + "?raw")}).then(module => ${parts.join(" + ")})`;
  };
  const { news, communities, about } = loadContent(root);
  const newsData = news.map(({value:item,directory}) => {
    const metadata = { id:item.id, kind:"news", title:item.title, digest:item.digest, publishedDate:item.publishedDate };
    return `{...${JSON.stringify(metadata)},thumbnail:${assetReference(directory,item.thumbnail)},body:${bodyLoader(directory,item.body)}}`;
  });
  const communityData = communities.map(({value:item,directory}) => `{...${JSON.stringify({slug:item.slug,name:item.name,domain:item.domain})},mp4:${assetReference(directory,item.mp4)},body:${bodyLoader(directory,item.body)}}`);
  const body = `{about:{summary:${JSON.stringify(about.value.summary)},body:${bodyLoader(about.directory,about.value.body)}},communities:[${communityData.join(",")}],news:[${newsData.join(",")}]}`;
  const preamble = [...imports].map(([file,name]) => `import ${name} from ${JSON.stringify(path.relative(path.dirname(output),file).split(path.sep).join("/")+"?url&no-inline")};`).join("\n");
  fs.mkdirSync(path.dirname(output),{recursive:true});
  fs.writeFileSync(output, `// Generated by scripts/prepare-content.mjs. Edit content/ instead.\n${preamble}\nimport type { ContentData } from "@/shared/types/content";\nconst assetUrl = (url: string) => url.replace(/[\\s<>"'()\\[\\]\u0060\\\\]/gu, character => encodeURIComponent(character).replace(/[!'()*]/g, character => "%" + character.charCodeAt(0).toString(16)));\nconst CONTENT_DATA: ContentData = ${body};\nexport default CONTENT_DATA;\n`);
  return {news:news.length,communities:communities.length,assets:imports.size};
}
